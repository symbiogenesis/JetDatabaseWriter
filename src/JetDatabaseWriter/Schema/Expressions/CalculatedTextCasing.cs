    internal static int Change(int character, bool upper)
    {
        ReadOnlySpan<int> ranges = upper ? UpperRanges : LowerRanges;
        int low = 0;
        int high = (ranges.Length / 4) - 1;
        while (low <= high)
        {
            int middle = low + ((high - low) / 2);
            int offset = middle * 4;
            int first = ranges[offset];
            int last = ranges[offset + 1];
            if (character < first)
            {
                high = middle - 1;
            }
            else if (character > last)
            {
                low = middle + 1;
            }
            else
            {
                return (character - first) % ranges[offset + 2] == 0
                    ? character + ranges[offset + 3]
                    : character;
            }
        }

        return character;
    }
